GLYPHS: dict[str, list[str]] = {ch: rows.split() for ch, rows in _RAW.items()}


def _gid(ch: str) -> str:
    return f"g{ord(ch):02X}"


def _path(rows: list[str]) -> str:
    """Pixels as one path, merging horizontal runs to keep files small."""
    parts = []
    for y, row in enumerate(rows):
        for m in re.finditer(r"#+", row):
            n = m.end() - m.start()
            parts.append(f"M{m.start()} {y}h{n}v1h-{n}z")
    return "".join(parts)


def text_width(s: str, scale: float) -> float:
    return (len(s) * ADVANCE - 1) * scale


def text(s: str, x: float, y: float, scale: float, fill: str | None = None, cls: str | None = None) -> str:
    """Unknown characters render blank but keep their width."""
    uses = "".join(
        f'<use href="#{_gid(c)}" x="{i * ADVANCE}"/>'
        for i, c in enumerate(s.upper())
        if c in GLYPHS and c != " "
    )
    attrs = f' fill="{fill}"' if fill else ""
    attrs += f' class="{cls}"' if cls else ""
    return f'<g transform="translate({x} {y}) scale({scale})"{attrs}>{uses}</g>'


def defs_for(body: str) -> str:
    """Glyph definitions for only the glyphs a document references."""
    used = sorted(set(re.findall(r'href="#(g[0-9A-F]+)"', body)))
    by_id = {_gid(ch): rows for ch, rows in GLYPHS.items()}
    return "".join(f'<path id="{g}" d="{_path(by_id[g])}"/>' for g in used if g in by_id)
